/**
 * Generates public/_redirects for Netlify.
 *
 * WHY THIS EXISTS, AND IT IS AN SEO DECISION NOT A CONVENIENCE
 * The brief asked for both /plumbing-{suburb} and /plumber-{suburb}. Two live,
 * indexable pages per suburb targeting "plumbing X" and "plumber X" would be
 * near-duplicates of each other, which is exactly what Google's spam policy on
 * doorway pages and scaled content abuse is written to catch. It would also
 * split the link equity for one suburb across two URLs.
 *
 * So both URLs exist and both work. /plumbing-{suburb}/ 301s to the canonical
 * /plumber-{suburb}/, which consolidates the signal onto one page that targets
 * both phrases in its title, H1 and body. Anyone who types, links or prints
 * either URL lands in the right place.
 *
 * Also redirects the old WordPress paths so nothing that is currently ranking
 * or linked drops to a 404 on cutover.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { suburbs } from '../src/data/suburbs.js';

const lines = [
  '# Generated by scripts/gen-redirects.mjs. Do not edit by hand.',
  '',
  '# --- Keyword alias: /plumbing-{suburb} consolidates onto /plumber-{suburb} ---',
];

for (const s of suburbs) {
  lines.push(`/plumbing-${s.slug}/*  /plumber-${s.slug}/  301!`);
  lines.push(`/plumbing-${s.slug}    /plumber-${s.slug}/  301!`);
}

lines.push('');
lines.push('# --- Careers. One canonical URL, a handful of aliases a human might type. ---');
lines.push('# /careers/plumbing-jobs-yeppoon/ carries BOTH "plumbing jobs Yeppoon" and');
lines.push('# "plumber jobs Yeppoon". A second page for the synonym would be a doorway.');
lines.push('# Note the ORDER: the canonical path is never matched by these rules, so the');
lines.push('# real page still wins. Do not add /careers/* here or it will shadow the page.');
const careersAliases = [
  '/careers',
  '/careers/',
  '/jobs',
  '/jobs/',
  '/plumber-jobs-yeppoon',
  '/plumber-jobs-yeppoon/',
  '/plumbing-jobs-yeppoon',
  '/plumbing-jobs-yeppoon/',
  '/work-with-us',
  '/work-with-us/',
  '/join-our-team',
  '/join-our-team/',
];
for (const from of careersAliases) lines.push(`${from}  /careers/plumbing-jobs-yeppoon/  301!`);

lines.push('');
lines.push('# --- Old WordPress URLs, so nothing currently linked or ranking 404s ---');
const legacy = [
  ['/about-us/*', '/about/'],
  ['/about/*', '/about/'], // the old /about/ was serving injected spam. Register row 14.
  ['/locations/*', '/areas-we-serve/'],
  ['/contact-us/*', '/contact/'],
  ['/renovations/*', '/services/renovations/'],
  ['/hot-water-installation-and-maintenance/*', '/services/hot-water/'],
  ['/emergency-plumbing/*', '/services/emergency-plumbing/'],
  ['/blocked-drains-and-maintenance/*', '/services/blocked-drains/'],
  ['/backflow-tmv-testing/*', '/services/backflow-tmv-testing/'],
  ['/gas-installation/*', '/services/gas-fitting/'],
  ['/storm-water-solutions-in-taranganba/*', '/plumber-taranganba/'],
  ['/blog/*', '/'],
  ['/wp-admin/*', '/'],
  ['/wp-login.php', '/'],
];
for (const [from, to] of legacy) lines.push(`${from}  ${to}  301!`);

mkdirSync(new URL('../public/', import.meta.url), { recursive: true });
writeFileSync(new URL('../public/_redirects', import.meta.url), lines.join('\n') + '\n');
console.log(`_redirects written: ${suburbs.length * 2 + careersAliases.length + legacy.length} rules`);
